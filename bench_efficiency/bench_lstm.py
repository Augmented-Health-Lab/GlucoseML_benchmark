"""Runtime benchmark for the Martinsson LSTM baseline (Keras/TF).

The LSTM cannot be capped with `--max-train-steps` like the PyTorch methods,
and it has no fixed epoch budget (`epochs=10000` + `EarlyStopping(patience=50)`),
so it gets two modes:

`throughput`  (default, ~2 min)
    Builds the exact model from `Original_Martinsson/models/lstm_experiment_keras.py`
    and times `fit` on synthetic windows for a few epochs, discarding epoch 1 as
    warm-up.  Also times `predict`.  Feeds sec/epoch and ms/window to aggregate.py.

`fewshot-real`
    Runs the real few-shot training (stride 240, so the training set is small)
    all the way to early stopping and reports the epoch count that actually
    converged.  That number is what the "as-configured" column needs -- without
    it there is no honest way to state the LSTM's real training cost.

    python bench_efficiency/bench_lstm.py --mode throughput
    python bench_efficiency/bench_lstm.py --mode fewshot-real --train-csv-dir hf_cache/train/mixed
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

# The method imports `tensorflow.keras.optimizers.legacy`, which only exists in
# Keras 2. This must be set before TensorFlow is imported anywhere.
os.environ.setdefault("TF_USE_LEGACY_KERAS", "1")

BENCH_DIR = Path(__file__).resolve().parent
REPO_ROOT = BENCH_DIR.parent
LSTM_DIR = REPO_ROOT / "2019Martinsson_et_al_LSTM"
sys.path.insert(0, str(BENCH_DIR))

import timing  # noqa: E402

# Matches the YAMLs generated by fullshot_lstm_clarke.py / fewshot_lstm_clarke.py.
CONTEXT_STEPS = 144
HORIZON_STEPS = 6
NB_LSTM_STATES = 256
BATCH_SIZE = 1024
PATIENCE = 50
LEARNING_RATE = 1e-3
SCALE = 0.01


def load_module(path: Path):
    import importlib.util

    spec = importlib.util.spec_from_file_location(path.stem, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Cannot import {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def build_model():
    """Reuse the method's own model/optimizer/loss definitions verbatim."""
    try:
        import tf_keras  # noqa: F401,PLC0415
    except ImportError:
        raise SystemExit(
            "The LSTM baseline needs Keras 2 (it imports "
            "`tensorflow.keras.optimizers.legacy`).\n"
            "    pip install tf_keras\n"
            "TF_USE_LEGACY_KERAS=1 is set automatically by this script."
        ) from None

    sys.path.insert(0, str(LSTM_DIR))
    model_mod = load_module(LSTM_DIR / "Original_Martinsson" / "models" / "lstm_experiment_keras.py")
    optim_mod = load_module(LSTM_DIR / "Original_Martinsson" / "optimizers" / "adam_keras.py")
    loss_mod = load_module(LSTM_DIR / "Original_Martinsson" / "loss_functions" / "nll_keras.py")

    loss_fn = loss_mod.load()
    # nll outputs (std, mu) -> 2 units per horizon step, as in run_training_from_yaml.
    out_dim = 2 if "tf_nll" in loss_fn.__name__ else 1
    model = model_mod.load(
        (CONTEXT_STEPS, 1),
        out_dim,
        {"nb_lstm_states": NB_LSTM_STATES, "activation_function": "exp"},
    )
    optimizer = optim_mod.load({"learning_rate": LEARNING_RATE})
    model.compile(optimizer=optimizer, loss=loss_fn)
    return model


class EpochTimer:
    """Keras callback recording per-epoch wall time."""

    def __new__(cls):
        import tensorflow as tf

        class _Cb(tf.keras.callbacks.Callback):
            def __init__(self) -> None:
                super().__init__()
                self.epoch_seconds: List[float] = []

            def on_epoch_begin(self, epoch, logs=None):  # noqa: ARG002
                self._t0 = time.perf_counter()

            def on_epoch_end(self, epoch, logs=None):  # noqa: ARG002
                self.epoch_seconds.append(time.perf_counter() - self._t0)

        return _Cb()


def mode_throughput(args: argparse.Namespace) -> Dict[str, Any]:
    import numpy as np

    model = build_model()
    params = timing.count_params(model)

    rng = np.random.default_rng(0)
    n = args.synthetic_windows
    # Realistic magnitude: glucose in mg/dL scaled by 0.01, as the YAMLs do.
    x = (rng.normal(140.0, 40.0, size=(n, CONTEXT_STEPS, 1)) * SCALE).astype("float32")
    y = (rng.normal(140.0, 40.0, size=(n, 1)) * SCALE).astype("float32")
    n_valid = max(1, int(0.1 * n))
    x_valid, y_valid = x[:n_valid], y[:n_valid]

    cb = EpochTimer()
    model.fit(
        x,
        y,
        validation_data=(x_valid, y_valid),
        epochs=args.epochs,
        batch_size=BATCH_SIZE,
        shuffle=False,
        verbose=2,
        callbacks=[cb],
    )
    # Epoch 1 carries graph tracing and cuDNN autotune; drop it.
    steady = cb.epoch_seconds[1:] or cb.epoch_seconds
    sec_per_epoch = sum(steady) / len(steady)

    # Inference: one warm-up pass, then the measured pass.
    x_infer = x[: args.infer_windows]
    model.predict(x_infer[: min(1024, len(x_infer))], batch_size=BATCH_SIZE, verbose=0)
    timing.sync()
    t0 = time.perf_counter()
    model.predict(x_infer, batch_size=BATCH_SIZE, verbose=0)
    timing.sync()
    infer_seconds = time.perf_counter() - t0

    train_windows = n + n_valid
    return {
        "mode": "throughput",
        "synthetic_train_windows": n,
        "synthetic_valid_windows": n_valid,
        "epochs_run": len(cb.epoch_seconds),
        "epoch_seconds": cb.epoch_seconds,
        "sec_per_epoch": sec_per_epoch,
        "sec_per_1k_train_windows": 1000.0 * sec_per_epoch / train_windows,
        "infer_windows": args.infer_windows,
        "infer_seconds": infer_seconds,
        "ms_per_window": 1000.0 * infer_seconds / args.infer_windows,
        **params,
        "peak_memory_mb": timing.peak_memory_mb(),
        "environment": timing.environment(),
    }


def mode_fewshot_real(args: argparse.Namespace) -> Dict[str, Any]:
    """Train few-shot for real and report the epoch count early stopping picks."""
    import numpy as np
    import tensorflow as tf

    sys.path.insert(0, str(LSTM_DIR))
    loader = load_module(LSTM_DIR / "datasets_loader" / "glucofm_bench.py")

    cfg = {
        "csv_path": str(Path(args.train_csv_dir) / "all"),
        "nb_past_steps": CONTEXT_STEPS,
        "nb_future_steps": HORIZON_STEPS,
        "train_fraction": 0.9,
        "valid_fraction": 0.1,
        "test_fraction": 0.0,
        "scale": SCALE,
        "stride": args.train_stride,
    }

    load_t0 = time.perf_counter()
    result = loader.load_dataset(cfg)
    load_seconds = time.perf_counter() - load_t0
    if result is None:
        raise SystemExit(f"Dataset loader returned None for {args.train_csv_dir}")
    x_train, y_train, x_valid, y_valid, _, _ = result

    model = build_model()
    params = timing.count_params(model)

    cb = EpochTimer()
    early = tf.keras.callbacks.EarlyStopping(
        monitor="val_loss", patience=PATIENCE, mode="min", restore_best_weights=True
    )
    t0 = time.perf_counter()
    history = model.fit(
        x_train,
        y_train,
        validation_data=(x_valid, y_valid),
        epochs=args.epochs_cap,
        batch_size=BATCH_SIZE,
        shuffle=False,
        verbose=2,
        callbacks=[cb, early],
    )
    total_seconds = time.perf_counter() - t0

    epochs_run = len(history.history.get("loss", []))
    steady = cb.epoch_seconds[1:] or cb.epoch_seconds
    best_epoch = int(np.argmin(history.history["val_loss"])) + 1

    return {
        "mode": "fewshot-real",
        "train_stride": args.train_stride,
        "data_load_seconds": load_seconds,
        "train_windows": int(x_train.shape[0]),
        "valid_windows": int(x_valid.shape[0]),
        "epochs_run": epochs_run,
        "best_epoch": best_epoch,
        "early_stopped": epochs_run < args.epochs_cap,
        "total_train_seconds": total_seconds,
        "sec_per_epoch": sum(steady) / len(steady),
        "epoch_seconds": cb.epoch_seconds,
        **params,
        "peak_memory_mb": timing.peak_memory_mb(),
        "environment": timing.environment(),
    }


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mode", choices=["throughput", "fewshot-real"], default="throughput")
    parser.add_argument("--synthetic-windows", type=int, default=20000)
    parser.add_argument("--epochs", type=int, default=4, help="throughput mode: epoch 1 is dropped.")
    parser.add_argument("--infer-windows", type=int, default=20000)
    parser.add_argument(
        "--train-csv-dir",
        type=Path,
        default=REPO_ROOT / "hf_cache" / "train" / "mixed",
        help="fewshot-real mode: folder holding the per-subject CSVs.",
    )
    parser.add_argument("--train-stride", type=int, default=240, help="fewshot-real mode.")
    parser.add_argument("--epochs-cap", type=int, default=10000, help="fewshot-real mode: matches the YAML.")
    parser.add_argument("--out-dir", type=Path, default=BENCH_DIR / "results")
    args = parser.parse_args(argv)

    if args.mode == "fewshot-real":
        marker = Path(args.train_csv_dir) / "all"
        if not marker.exists():
            marker.parent.mkdir(parents=True, exist_ok=True)
            marker.touch()  # the loader keys "load every CSV here" off this file
        payload = mode_fewshot_real(args)
    else:
        payload = mode_throughput(args)

    out_path = args.out_dir / f"throughput_lstm_{args.mode}.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(payload, indent=2, default=str))

    print("\n=== summary ===")
    print(json.dumps({k: v for k, v in payload.items() if k != "epoch_seconds"}, indent=2, default=str))
    print(f"\nWrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
